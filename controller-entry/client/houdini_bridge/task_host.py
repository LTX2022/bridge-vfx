"""Public task-host lifecycle launcher (client side).

    python -m houdini_bridge task-host start --task-id T --work-dir D --addon-root R
    python -m houdini_bridge task-host stop  --work-dir D

Contract (core-chain rework round 2):
  * The runner uses the add-on's PUBLIC module surface only (no sys.modules
    private bridging) and receives every parameter as an argument.
  * The ready receipt is bound to a launcher-generated ``launch_nonce`` plus
    task, pid, session, generation and add-on build; the launcher verifies the
    nonce before reporting readiness.
  * No implicit build/cook happens at start. Warmup is an explicit opt-in
    (``--warmup``) for controllers that accept its cost; it is not part of the
    default path and never runs before the budget of a submitted operation.
  * Starting into a work directory with a live owner is refused (ACTIVE_OWNER);
    the previous receipt is never wiped. A dead owner is cleaned up.
  * Start timeout moves the child into an explicit reclaim: stop file, grace
    period, then termination of the launcher's OWN child only.
  * ``stop`` confirms actual process exit (pid from the receipt), not just the
    shutdown file; the shutdown file alone is necessary but not sufficient.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
import uuid
from contextlib import contextmanager
from pathlib import Path
from dcc_task_runtime.canonical import canonical_json, canonical_sha256
from dcc_task_runtime.platform_support import (lock_file, unlock_file, pid_alive,
    ensure_private_directory, open_private_file, remove_owned_path)

class _RunnerTemplate(str):
    def format(self, *, writer_executable=None, **parameters):
        # Legacy runners omit the optional public API argument entirely.
        argument = ("writer_executable={!r},".format(writer_executable)
                    if writer_executable is not None else "")
        return super().format(writer_executable=argument, **parameters)


RUNNER_TEMPLATE = _RunnerTemplate('''# Generated by houdini_bridge.task_host — generic task host runner (public API).
import sys, time
ADDON_LIBS = {addon_libs!r}
sys.path.insert(0, ADDON_LIBS)
import houdini_bridge_addon
receipt = houdini_bridge_addon.task_host_serve(
    task_id={task_id!r},
    stop_file={stop_file!r},
    ready_file={ready_file!r},
    poll_seconds={poll_seconds!r},
    max_seconds={max_seconds!r},
    warmup={warmup!r},
    launch_nonce={launch_nonce!r},
    {writer_executable}
)
print("TASK_HOST_RECEIPT", receipt.get("stop_reason"), flush=True)
''')

DEFAULT_HYTHON_CANDIDATES = (
    "/Applications/Houdini/Houdini21.0.631/Frameworks/Houdini.framework/Versions/21.0/Resources/bin/hython",
    "/Applications/Houdini/Houdini22.0.429/Frameworks/Houdini.framework/Versions/22.0/Resources/bin/hython",
    "/Applications/Houdini/Houdini22.0.459/Frameworks/Houdini.framework/Versions/22.0/Resources/bin/hython",
)

WORKDIR_READY = "host.ready"
WORKDIR_STOP = "host.stop"

# Children THIS launcher process started; the launcher must reap them so a
# stopped host cannot linger as a zombie and defeat pid-liveness checks.
_ACTIVE_CHILDREN: "dict[int, subprocess.Popen]" = {}


def _find_hython(explicit: "str | None") -> Path:
    if explicit:
        path = Path(explicit).expanduser()
        if not path.is_file():
            raise SystemExit("houdini-bin does not exist: {}".format(path))
        return path
    for candidate in DEFAULT_HYTHON_CANDIDATES:
        path = Path(candidate)
        if path.is_file():
            return path
    raise SystemExit("no hython found; pass --houdini-bin")


def _pid_alive(pid) -> bool:
    return pid_alive(pid)


def active_owner_present(workdir: Path) -> bool:
    """True when a ready receipt exists AND its process is still alive."""
    ready = Path(workdir) / WORKDIR_READY
    if not ready.is_file():
        return False
    try:
        receipt = json.loads(ready.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return False
    return _pid_alive(receipt.get("pid"))


HOST_PROTOCOL_VERSION = "task-host/1.0"


@contextmanager
def _owner_lock(workdir: Path):
    """Atomically claim the work directory for ONE launcher.

    Two launchers racing through the ``active_owner_present`` check would both
    start a host; the exclusive owner lock serializes them, so the loser sees
    a live owner (or claims cleanly after the winner releases).  A crashed
    launcher releases the lock by construction (kernel flock cleanup).
    """
    lock_path = workdir / ".owner-lock"
    descriptor = open_private_file(lock_path, os.O_CREAT | os.O_RDWR)
    acquired = False
    try:
        try:
            lock_file(descriptor, blocking=False)
            acquired = True
        except OSError as exc:
            raise BlockingIOError("owner lock is held by another launcher") from exc
        yield
    finally:
        try:
            if acquired:
                unlock_file(descriptor)
        finally:
            os.close(descriptor)


def _verify_receipt(receipt: dict, task_id: str) -> list[str]:
    """Full receipt verification: identity, liveness, protocol and build."""
    problems: list[str] = []
    pid = receipt.get("pid")
    if not _pid_alive(pid):
        problems.append("pid {} is not alive".format(pid))
    if str(receipt.get("task_id") or "") != str(task_id):
        problems.append("task_id mismatch: {!r}".format(receipt.get("task_id")))
    if str(receipt.get("protocol_version") or "") != HOST_PROTOCOL_VERSION:
        problems.append("protocol_version mismatch: {!r}".format(receipt.get("protocol_version")))
    addon_sha = str(receipt.get("addon_sha256") or "")
    if len(addon_sha) != 64 or any(c not in "0123456789abcdef" for c in addon_sha):
        problems.append("addon_sha256 missing or malformed")
    port = receipt.get("port")
    if not isinstance(port, int) or port <= 0:
        problems.append("port missing or invalid: {!r}".format(port))
    return problems


def _software_launch_script(args: argparse.Namespace) -> Path | None:
    if not hasattr(args, "software_launch_script"):
        return None
    if (getattr(args, "evidence_source", None) != "software_test"
            or getattr(args, "allow_software_processes", False) is not True):
        raise ValueError("SOFTWARE_PROCESS_BOUNDARY_NOT_AUTHORIZED")
    script = Path(str(args.software_launch_script or ""))
    if not script.is_absolute() or script.is_symlink() or not script.is_file():
        raise ValueError("SOFTWARE_LAUNCH_SCRIPT_INVALID")
    digest = hashlib.sha256(script.read_bytes()).hexdigest()
    if (hasattr(args, "software_launch_script_sha256")
            and args.software_launch_script_sha256 != digest):
        raise ValueError("SOFTWARE_LAUNCH_SCRIPT_CHANGED")
    return script.resolve()


def _writer_executable(args: argparse.Namespace) -> dict | None:
    writer = getattr(args, "writer_executable", None)
    if writer is None:
        return None
    if not isinstance(writer, dict) or writer.get("version") != getattr(args, "version", None):
        raise ValueError("WRITER_EXECUTABLE_INVALID")
    from dcc_task_runtime.process_image import freeze_executable
    frozen = freeze_executable(writer["image"]["path"], writer["version"], writer["image"]["sha256"])
    if canonical_json(frozen) != canonical_json(writer):
        raise ValueError("WRITER_EXECUTABLE_CHANGED")
    return frozen


def start(args: argparse.Namespace) -> int:
    _software_launch_script(args)
    _writer_executable(args)
    workdir = Path(args.work_dir).expanduser().resolve()
    scope_binding = (getattr(args, 'resource_budget', None) or {}).get('native_scope')
    if scope_binding is not None:
        from dcc_task_runtime.native_scope import NativeScope
        scope = NativeScope(scope_binding)
        if not getattr(args, 'houdini_bin', None) or not getattr(args, 'supervisor_executable', None):
            raise ValueError('NATIVE_SCOPE_HOST_EXECUTABLE_REQUIRED')
        scope.validate_host('houdini', getattr(args, 'version', None), _find_hython(args.houdini_bin),
            Path(args.supervisor_executable).resolve(), project_color=getattr(args, 'project_color', None),
            writer=getattr(args, 'writer_executable', None),
            allow_missing_writer=(getattr(args, 'evidence_source', None) == 'software_test'
                                  and getattr(args, 'allow_software_processes', False) is True))
        environment = getattr(args, 'environment', {}) or {}
        paths = [workdir]
        for key in ('HOUDINI_BRIDGE_STATE_DIR', 'HOUDINI_BRIDGE_TASK_STATE_DIR', 'BRIDGE_SKILLS_STATE_ROOT',
                    'BRIDGE_ARTIFACT_LEDGER_ROOT', 'BRIDGE_SKILLS_SCHEDULER_ROOT'):
            if not environment.get(key): raise ValueError('NATIVE_SCOPE_HOST_PATH_REQUIRED:' + key)
            paths.append(Path(environment[key]).resolve())
        if any(not path.is_relative_to(scope.root) for path in paths):
            raise ValueError('NATIVE_SCOPE_HOST_PATH_OUTSIDE_ROOT')
    ensure_private_directory(workdir)
    ready_file = workdir / WORKDIR_READY
    stop_file = workdir / WORKDIR_STOP
    try:
        lock_ctx = _owner_lock(workdir)
        lock_ctx.__enter__()
    except BlockingIOError:
        existing = json.loads(ready_file.read_text(encoding="utf-8")) if ready_file.is_file() else {}
        print(json.dumps({"error": "ACTIVE_OWNER", "pid": existing.get("pid"),
                          "hint": "another launcher owns this work directory"}, ensure_ascii=False))
        return 5
    try:
        return _start_locked(args, workdir, ready_file, stop_file)
    finally:
        lock_ctx.__exit__(None, None, None)


def _host_budget_seconds(args: argparse.Namespace) -> float:
    """仅已认证几何范围使用既定Houdini角色上限，其余宿主保持120秒。"""
    seconds = float(args.max_seconds or 120)
    binding = (getattr(args, 'resource_budget', None) or {}).get('native_scope')
    if binding is not None:
        from dcc_task_runtime.native_scope import NativeScope, GEOMETRY_RESOURCE_PROFILE
        scope = NativeScope(binding)
        if scope.resource_profile == GEOMETRY_RESOURCE_PROFILE:
            return min(seconds, scope.role_seconds('houdini-host'))
    return min(seconds, 120)


def _start_locked(args: argparse.Namespace, workdir: Path, ready_file: Path, stop_file: Path) -> int:
    software_script = _software_launch_script(args)
    writer_executable = _writer_executable(args)
    if active_owner_present(workdir):
        existing = json.loads(ready_file.read_text(encoding="utf-8"))
        print(json.dumps({"error": "ACTIVE_OWNER", "pid": existing.get("pid"),
                          "hint": "stop the active host or use a different work directory"}, ensure_ascii=False))
        return 5
    for stale in (ready_file, stop_file, workdir / (WORKDIR_READY + ".shutdown.json")):
        if stale.exists():
            remove_owned_path(stale, owned_root=workdir)
    addon_root = Path(args.addon_root).expanduser().resolve()
    addon_libs = addon_root / ("python3.13libs" if str(getattr(args,"version", "")).startswith("22.") else "python3.11libs")
    impl = addon_root / "_impl" / "houdini_bridge_addon.py"
    if not impl.is_file():
        print(json.dumps({"error": "ADDON_NOT_FOUND", "addon_root": str(addon_root)}, ensure_ascii=False))
        return 6
    launch_nonce = uuid.uuid4().hex
    runner_path = workdir / "task_host_runner.py"
    runner_path.write_text(RUNNER_TEMPLATE.format(
        addon_libs=str(addon_libs), task_id=args.task_id, stop_file=str(stop_file),
        ready_file=str(ready_file), poll_seconds=args.poll_seconds, max_seconds=args.max_seconds,
        warmup=bool(args.warmup), launch_nonce=launch_nonce, writer_executable=writer_executable,
    ), encoding="utf-8")
    hython = _find_hython(args.houdini_bin)
    from dcc_task_runtime.owned_process import launch, _atomic
    identity = {"task_id": args.task_id, "launch_nonce": launch_nonce}
    writer_options = {}
    if writer_executable is not None:
        identity["writer_executable_sha256"] = canonical_sha256(writer_executable)
        writer_options["writer_executable"] = writer_executable
    supervisor_dir = workdir / ("supervisor-" + launch_nonce)
    log = supervisor_dir / "child.stdout.log"
    stderr_log = supervisor_dir / "child.stderr.log"
    environment = os.environ.copy()
    environment.update(dict(getattr(args, "environment", {}) or {}))
    if (getattr(args, 'resource_budget', None) or {}).get('native_scope') is not None:
        temporary = ensure_private_directory(workdir/'tmp')
        preferences = ensure_private_directory(workdir/'houdini-preferences')
        environment.update(TMPDIR=str(temporary), PYTHONDONTWRITEBYTECODE='1',
                           HOUDINI_USER_PREF_DIR=str(preferences/'__HVER__'))
    environment["BRIDGE_OWNED_SUPERVISOR_DIR"] = str(supervisor_dir)
    environment["BRIDGE_OWNED_SUPERVISOR_IDENTITY"] = json.dumps(identity, sort_keys=True)
    argv = [str(hython)]
    if software_script is not None:
        argv.append(str(software_script))
    argv.append(str(runner_path))
    scope_options = ({"scope_role":"houdini-host", "scope_heavy":False}
                     if (getattr(args, "resource_budget", None) or {}).get("native_scope") is not None else {})
    process = launch(argv, directory=supervisor_dir,
                     identity=identity, supervisor_executable=str(Path(getattr(args, "supervisor_executable", None) or sys.executable).resolve()),
                     env=environment, budget_seconds=_host_budget_seconds(args),
                     resource_budget=getattr(args,"resource_budget",None), **scope_options, **writer_options)
    _atomic(workdir / "supervisor-binding.json", {"directory": str(supervisor_dir), "identity": identity})
    _ACTIVE_CHILDREN[process.pid] = process
    deadline = time.monotonic() + args.ready_timeout
    receipt = None
    while time.monotonic() < deadline:
        if ready_file.is_file():
            try:
                receipt = json.loads(ready_file.read_text(encoding="utf-8"))
            except ValueError:
                receipt = None
            if receipt and receipt.get("launch_nonce") == launch_nonce:
                # Full identity verification before reporting readiness: a
                # nonce match alone does not prove the process is ours.
                problems = _verify_receipt(receipt, args.task_id)
                if receipt.get("pid") != process.pid:
                    problems.append("receipt pid is not the supervised child")
                if problems:
                    _reclaim_child(stop_file, process)
                    print(json.dumps({"error": "RECEIPT_VERIFICATION_FAILED",
                                      "problems": problems, "reclaimed": True,
                                      "log": str(log), "stderr_log": str(stderr_log)}, ensure_ascii=False))
                    return 7
                receipt["launcher_generation"] = uuid.uuid4().hex[:12]
                receipt["runner"] = str(runner_path)
                print(json.dumps(receipt, ensure_ascii=False, indent=1))
                return 0
        if process.poll() is not None:
            print(json.dumps({"error": "HOST_EXITED", "returncode": process.returncode, "log": str(log), "stderr_log": str(stderr_log)}, ensure_ascii=False))
            return 2
        time.sleep(0.25)
    # ready timeout: explicit reclaim of our own child
    _reclaim_child(stop_file, process, grace=5.0)
    print(json.dumps({"error": "HOST_READY_TIMEOUT_RECLAIMED", "reclaimed": True,
                      "returncode": process.returncode, "log": str(log), "stderr_log": str(stderr_log)}, ensure_ascii=False))
    return 3


def _reclaim_child(stop_file: Path, process: subprocess.Popen, grace: float = 15.0) -> bool:
    """Stop-file, grace, terminate, kill — the launcher's OWN child only."""
    reclaimed = False
    try:
        stop_file.write_text("stop", encoding="utf-8")
    except OSError:
        pass
    try:
        process.wait(timeout=grace)
        return True
    except subprocess.TimeoutExpired:
        pass
    process.terminate()
    try:
        process.wait(timeout=10)
        reclaimed = True
    except subprocess.TimeoutExpired:
        process.kill()
        try:
            process.wait(timeout=10)
            reclaimed = True
        except subprocess.TimeoutExpired:
            reclaimed = False
    return reclaimed


def stop(args: argparse.Namespace) -> int:
    workdir = Path(args.work_dir).expanduser().resolve()
    ready_file = workdir / WORKDIR_READY
    stop_file = workdir / WORKDIR_STOP
    if not ready_file.is_file():
        print(json.dumps({"error": "NO_READY_RECEIPT", "work_dir": str(workdir)}, ensure_ascii=False))
        return 2
    receipt = json.loads(ready_file.read_text(encoding="utf-8"))
    stop_file.write_text("stop", encoding="utf-8")
    shutdown_file = workdir / (WORKDIR_READY + ".shutdown.json")
    deadline = time.monotonic() + args.timeout
    while time.monotonic() < deadline and not shutdown_file.is_file():
        time.sleep(0.25)
    # the shutdown file is necessary but not sufficient: confirm process exit
    pid = receipt.get("pid")
    child = _ACTIVE_CHILDREN.pop(int(pid), None) if isinstance(pid, int) else None
    if child is None and (workdir / "supervisor-binding.json").is_file():
        from dcc_task_runtime.owned_process import OwnedProcessHandle
        binding = json.loads((workdir / "supervisor-binding.json").read_text(encoding="utf-8"))
        expected = workdir / ("supervisor-" + str(receipt.get("launch_nonce") or ""))
        if Path(binding["directory"]).absolute() == expected.absolute():
            child = OwnedProcessHandle(expected, binding["identity"])
            if child.pid != pid:
                child = None
    exit_deadline = time.monotonic() + max(float(args.timeout), float(getattr(args, "exit_grace", 15.0)))
    confirmed_exit = False
    while time.monotonic() < exit_deadline:
        if child is not None and child.poll() is not None:
            confirmed_exit = True  # reaped: the launcher's own child is gone
            break
        time.sleep(0.25)
    shutdown = json.loads(shutdown_file.read_text(encoding="utf-8")) if shutdown_file.is_file() else {}
    result = {"pid": pid, "stop_reason": shutdown.get("stop_reason"),
              "shutdown_receipt_seen": shutdown_file.is_file(),
              "confirmed_exit": confirmed_exit,
              "heavy_slot_released": bool(shutdown.get("stopped_cleanly")) and confirmed_exit}
    print(json.dumps(result, ensure_ascii=False, indent=1))
    if not confirmed_exit:
        return 4
    return 0 if result["heavy_slot_released"] else 1


def register(commands: argparse.ArgumentParser) -> None:
    parser = commands.add_parser("task-host", help="run a headless Houdini task host (start/stop)")
    sub = parser.add_subparsers(dest="task_host_command", required=True)
    p_start = sub.add_parser("start", help="start a task host and print the ready receipt")
    p_start.add_argument("--task-id", required=True)
    p_start.add_argument("--work-dir", required=True)
    p_start.add_argument("--addon-root", required=True, help="directory containing python3.11libs/ and _impl/ of the bridge add-on")
    p_start.add_argument("--houdini-bin", default=None)
    p_start.add_argument("--max-seconds", type=float, default=None)
    p_start.add_argument("--ready-timeout", type=float, default=90.0)
    p_start.add_argument("--poll-seconds", type=float, default=0.05)
    p_start.add_argument("--warmup", action="store_true", help="explicit opt-in: warm solver caches before serving (counted in the receipt)")
    p_start.set_defaults(func=start)
    p_stop = sub.add_parser("stop", help="cooperatively stop the task host in a work directory")
    p_stop.add_argument("--work-dir", required=True)
    p_stop.add_argument("--timeout", type=float, default=30.0)
    p_stop.set_defaults(func=stop)
